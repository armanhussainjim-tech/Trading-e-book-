import { StrategyOutline } from './user100StrategiesOutline';

export interface CleanStrategyContent {
  psychology: string;
  setup: string;
  buyRules: string[];
  sellRules: string[];
  riskManagement: {
    stopLoss: string;
    takeProfit: string;
    rrr: string;
    riskPerTrade: string;
  };
  chartGuide: string;
}

export function getCleanStrategyContent(outline: StrategyOutline): CleanStrategyContent {
  const { banglaTitle, englishTitle, categoryNumber, setupType, defaultTimeframe } = outline;

  // 1. Basic Price Action (1-10)
  if (categoryNumber === 1) {
    return getCategory1Content(outline);
  }
  // 2. Single Candlestick (11-20)
  if (categoryNumber === 2) {
    return getCategory2Content(outline);
  }
  // 3. Multiple Candlestick (21-30)
  if (categoryNumber === 3) {
    return getCategory3Content(outline);
  }
  // 4. Moving Average (31-40)
  if (categoryNumber === 4) {
    return getCategory4Content(outline);
  }
  // 5. Oscillator & Momentum (41-50)
  if (categoryNumber === 5) {
    return getCategory5Content(outline);
  }
  // 6. Volatility & Band (51-60)
  if (categoryNumber === 6) {
    return getCategory6Content(outline);
  }
  // 7. Chart Patterns (61-70)
  if (categoryNumber === 7) {
    return getCategory7Content(outline);
  }
  // 8. Trend & Breakout (71-80)
  if (categoryNumber === 8) {
    return getCategory8Content(outline);
  }
  // 9. Multi-Indicator (81-90)
  if (categoryNumber === 9) {
    return getCategory9Content(outline);
  }
  // 10. Advanced / SMC (91-100)
  return getCategory10Content(outline);
}

